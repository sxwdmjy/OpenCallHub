package com.och.quality.application;

import com.och.quality.domain.QualityAppeal;
import com.och.quality.domain.QualityScore;
import com.och.quality.domain.QualityTemplate;
import com.och.quality.mapper.QualityAppealMapper;
import com.och.quality.mapper.QualityScoreMapper;
import com.och.quality.mapper.QualityTemplateMapper;
import com.och.quality.service.impl.QualityServiceImpl;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.springframework.test.util.ReflectionTestUtils;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

/**
 * QualityServiceImpl 单元测试。
 */
@ExtendWith(MockitoExtension.class)
@DisplayName("QualityServiceImpl 单元测试")
class QualityServiceTest {

    @Mock
    private QualityTemplateMapper templateMapper;

    @Mock
    private QualityScoreMapper scoreMapper;

    @Mock
    private QualityAppealMapper appealMapper;

    @InjectMocks
    private QualityServiceImpl service;

    @BeforeEach
    void setUp() { ReflectionTestUtils.setField(service, "baseMapper", templateMapper); }

    // ==================== 质检模板 ====================

    @Test
    @DisplayName("listTemplates: 返回已发布的模板列表")
    void shouldReturnPublishedTemplates() {
        // given
        QualityTemplate t1 = new QualityTemplate();
        t1.setId(1L);
        t1.setTemplateName("服务规范模板");
        t1.setTemplateCode("QT-001");
        t1.setPublished(true);

        QualityTemplate t2 = new QualityTemplate();
        t2.setId(2L);
        t2.setTemplateName("合规检查模板");
        t2.setTemplateCode("QT-002");
        t2.setPublished(true);

        when(templateMapper.selectList(any())).thenReturn(Arrays.asList(t1, t2));

        // when
        List<QualityTemplate> result = service.listTemplates();

        // then
        assertThat(result).hasSize(2);
        assertThat(result.get(0).getTemplateName()).isEqualTo("服务规范模板");
        assertThat(result.get(1).getTemplateName()).isEqualTo("合规检查模板");
        assertThat(result.get(0).getPublished()).isTrue();
        assertThat(result.get(1).getPublished()).isTrue();
        verify(templateMapper).selectList(any());
    }

    @Test
    @DisplayName("listTemplates: 无已发布模板时返回空列表")
    void shouldReturnEmptyListWhenNoPublishedTemplates() {
        // given
        when(templateMapper.selectList(any())).thenReturn(Collections.emptyList());

        // when
        List<QualityTemplate> result = service.listTemplates();

        // then
        assertThat(result).isEmpty();
        verify(templateMapper).selectList(any());
    }

    @Test
    @DisplayName("createTemplate: 创建模板时自动生成编码并默认未发布")
    void shouldCreateTemplateWithAutoGeneratedCode() {
        // given
        QualityTemplate input = new QualityTemplate();
        input.setTemplateName("新模板");
        input.setRulesJson("{\"items\":[]}");
        input.setTotalScore(100);
        input.setPassScore(60);

        // when
        QualityTemplate result = service.createTemplate(input);

        // then
        assertThat(result.getTemplateCode()).startsWith("QT-");
        assertThat(result.getTemplateCode()).hasSize(9); // QT- + 6位
        assertThat(result.getPublished()).isFalse();
        assertThat(result.getTemplateName()).isEqualTo("新模板");
        verify(templateMapper).insert(eq(input));
    }

    @Test
    @DisplayName("createTemplate: 显式设置 published=true 时应保留")
    void shouldKeepPublishedWhenExplicitlySetTrue() {
        // given
        QualityTemplate input = new QualityTemplate();
        input.setTemplateName("已发布模板");
        input.setPublished(true);

        // when
        QualityTemplate result = service.createTemplate(input);

        // then
        assertThat(result.getPublished()).isTrue();
        verify(templateMapper).insert(eq(input));
    }

    // ==================== 质检评分 ====================

    @Test
    @DisplayName("submitScore: 总分 >= 模板及格分 -> passScore=1（及格）")
    void shouldMarkPassedWhenTotalScoreReachesPassThreshold() {
        // given
        QualityTemplate template = new QualityTemplate();
        template.setId(1L);
        template.setPassScore(60);

        QualityScore input = new QualityScore();
        input.setTemplateId(1L);
        input.setTotalScore(85);
        input.setScorerId(100L);
        input.setCallRecordId(200L);
        input.setType("MANUAL");

        when(templateMapper.selectById(eq(1L))).thenReturn(template);

        // when
        QualityScore result = service.submitScore(input);

        // then
        assertThat(result.getPassScore()).isEqualTo(1);
        verify(templateMapper).selectById(eq(1L));
        verify(scoreMapper).insert(eq(input));
    }

    @Test
    @DisplayName("submitScore: 总分 < 模板及格分 -> passScore=0（不及格）")
    void shouldMarkFailedWhenTotalScoreBelowPassThreshold() {
        // given
        QualityTemplate template = new QualityTemplate();
        template.setId(1L);
        template.setPassScore(60);

        QualityScore input = new QualityScore();
        input.setTemplateId(1L);
        input.setTotalScore(45);
        input.setScorerId(100L);
        input.setType("AI");

        when(templateMapper.selectById(eq(1L))).thenReturn(template);

        // when
        QualityScore result = service.submitScore(input);

        // then
        assertThat(result.getPassScore()).isEqualTo(0);
        verify(scoreMapper).insert(eq(input));
    }

    @Test
    @DisplayName("submitScore: 未关联模板 -> passScore=0")
    void shouldDefaultPassScoreToZeroWhenNoTemplate() {
        // given
        QualityScore input = new QualityScore();
        input.setTotalScore(90);
        input.setScorerId(100L);
        // templateId is null

        // when
        QualityScore result = service.submitScore(input);

        // then
        assertThat(result.getPassScore()).isEqualTo(0);
        verify(templateMapper, never()).selectById(any());
        verify(scoreMapper).insert(eq(input));
    }

    @Test
    @DisplayName("submitScore: 模板存在但 passScore 为 null -> passScore=0")
    void shouldDefaultPassScoreToZeroWhenTemplatePassScoreIsNull() {
        // given
        QualityTemplate template = new QualityTemplate();
        template.setId(1L);
        // passScore is null

        QualityScore input = new QualityScore();
        input.setTemplateId(1L);
        input.setTotalScore(90);

        when(templateMapper.selectById(eq(1L))).thenReturn(template);

        // when
        QualityScore result = service.submitScore(input);

        // then
        assertThat(result.getPassScore()).isEqualTo(0);
        verify(scoreMapper).insert(eq(input));
    }

    @Test
    @DisplayName("submitScore: totalScore 等于 passScore -> passScore=1（及格）")
    void shouldMarkPassedWhenTotalScoreEqualsPassThreshold() {
        // given
        QualityTemplate template = new QualityTemplate();
        template.setId(1L);
        template.setPassScore(60);

        QualityScore input = new QualityScore();
        input.setTemplateId(1L);
        input.setTotalScore(60);

        when(templateMapper.selectById(eq(1L))).thenReturn(template);

        // when
        QualityScore result = service.submitScore(input);

        // then
        assertThat(result.getPassScore()).isEqualTo(1);
    }

    // ==================== 质检申诉 ====================

    @Test
    @DisplayName("submitAppeal: 关联评分存在时提交成功，状态为 PENDING")
    void shouldSubmitAppealWithPendingState() {
        // given
        QualityScore existingScore = new QualityScore();
        existingScore.setId(100L);
        existingScore.setTotalScore(45);

        QualityAppeal input = new QualityAppeal();
        input.setScoreId(100L);
        input.setAppellantId(200L);
        input.setReason("评分过低，请重新评估");

        when(scoreMapper.selectById(eq(100L))).thenReturn(existingScore);

        // when
        QualityAppeal result = service.submitAppeal(input);

        // then
        assertThat(result.getState()).isEqualTo("PENDING");
        assertThat(result.getScoreId()).isEqualTo(100L);
        assertThat(result.getAppellantId()).isEqualTo(200L);
        verify(scoreMapper).selectById(eq(100L));
        verify(appealMapper).insert(eq(input));
    }

    @Test
    @DisplayName("submitAppeal: 关联评分不存在时抛出 IllegalArgumentException")
    void shouldThrowExceptionWhenScoreNotFound() {
        // given
        QualityAppeal input = new QualityAppeal();
        input.setScoreId(999L);
        input.setAppellantId(200L);
        input.setReason("评分不合理");

        when(scoreMapper.selectById(eq(999L))).thenReturn(null);

        // when / then
        assertThatThrownBy(() -> service.submitAppeal(input))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("申诉关联的评分不存在")
                .hasMessageContaining("999");
    }

    @Test
    @DisplayName("reviewAppeal: 审核通过 -> 状态更新为 APPROVED，原评分备注更新")
    void shouldApproveAppealAndUpdateScoreComment() {
        // given
        QualityAppeal existingAppeal = new QualityAppeal();
        existingAppeal.setId(1L);
        existingAppeal.setScoreId(100L);
        existingAppeal.setState("PENDING");

        QualityScore existingScore = new QualityScore();
        existingScore.setId(100L);
        existingScore.setTotalScore(45);

        when(appealMapper.selectById(eq(1L))).thenReturn(existingAppeal);
        when(scoreMapper.selectById(eq(100L))).thenReturn(existingScore);

        // when
        service.reviewAppeal(1L, true, "同意申诉，调整为75分");

        // then
        verify(appealMapper).selectById(eq(1L));
        verify(scoreMapper).selectById(eq(100L));
        verify(appealMapper).updateById(argThat(appeal ->
                "APPROVED".equals(appeal.getState())
                        && "同意申诉，调整为75分".equals(appeal.getReviewComment())
                        && appeal.getReviewedAt() != null
        ));
        verify(scoreMapper).updateById(argThat(score ->
                score.getId().equals(100L)
                        && score.getComment() != null
                        && score.getComment().startsWith("【申诉通过】")
        ));
    }

    @Test
    @DisplayName("reviewAppeal: 审核驳回 -> 状态更新为 REJECTED，不更新原评分")
    void shouldRejectAppealWithoutUpdatingScore() {
        // given
        QualityAppeal existingAppeal = new QualityAppeal();
        existingAppeal.setId(1L);
        existingAppeal.setScoreId(100L);
        existingAppeal.setState("PENDING");

        when(appealMapper.selectById(eq(1L))).thenReturn(existingAppeal);

        // when
        service.reviewAppeal(1L, false, "申诉证据不足，维持原判");

        // then
        verify(appealMapper).selectById(eq(1L));
        verify(appealMapper).updateById(argThat(appeal ->
                "REJECTED".equals(appeal.getState())
                        && "申诉证据不足，维持原判".equals(appeal.getReviewComment())
                        && appeal.getReviewedAt() != null
        ));
        verify(scoreMapper, never()).updateById(any());
    }

    @Test
    @DisplayName("reviewAppeal: 申诉不存在时抛出 IllegalArgumentException")
    void shouldThrowExceptionWhenAppealNotFound() {
        // given
        when(appealMapper.selectById(eq(999L))).thenReturn(null);

        // when / then
        assertThatThrownBy(() -> service.reviewAppeal(999L, true, "通过"))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("申诉不存在")
                .hasMessageContaining("999");
    }
}
